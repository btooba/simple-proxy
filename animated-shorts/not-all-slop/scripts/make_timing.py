"""Turn words.json into assets/timing.js: named cue times the 3D scene reacts to."""
import json, pathlib, re
P = pathlib.Path(__file__).resolve().parent.parent
W = json.loads((P / "words.json").read_text())
norm = lambda w: re.sub(r"[^a-z0-9]", "", w.lower())
def at(word, n=1, end=False):
    k = 0
    for w in W:
        if norm(w["w"]) == word:
            k += 1
            if k == n:
                return w["e"] if end else w["s"]
    raise SystemExit(f"missing word {word} #{n}")
CUES = dict(
    typed=("typed",), n70=("70000",), filter=("filter",), hide=("hide",), july=("july",), build=("build",),
    type=("type",), sentence=("sentence",), game=("game",), code=("code",), art=("art",), half=("half",),
    help=("help",), clickers=("clickers",), copycats=("copycats",), people2=("people", 2), counter=("counterstrike",),
    exactly=("exactly",), makers=("makers",), peak=("peak",), copy=("copy",), tell=("tell",), pirate=("pirate",),
    ripoff=("ripoff",), so=("so",), why=("why",), p80=("80",), see=("ai", 3), camera=("camera",),  # "see": start of "AI is like the camera" (the outside voice skips "You see,")
    everybody=("everybody",), photographer=("photographer",), slop3=("slop", 3), skipping=("skipping",), fun=("fun",),
    made=("made",), troll1=("troll",), but=("but",), flipping=("flipping",), screen=("screen",), dropping=("dropping",),
    banana=("banana",), launching=("launching",), other=("other",), bomb=("bomb",), funny=("funny",), video=("video",), also=("also",),
    did=("did",), slop4=("slop", 4), troll2=("troll", 2), coming=("coming",), first=("first",), limited=("limited",),
    og=("og",), pet=("pet",), revealing=("revealing",), follow=("follow",), miss=("miss",),
)
T = {k: round(at(*v), 3) for k, v in CUES.items()}
T["voiceEnd"] = W[-1]["e"]
T["end"] = round(int((W[-1]["e"] + 0.3) * 10 + 0.999) / 10, 1)  # video length: voice end + ~0.3 s, whole tenths
(P / "assets" / "timing.js").write_text("// generated by scripts/make_timing.py from words.json\nexport const T = " + json.dumps(T) + ";\n")
print(json.dumps(T))
